/**
 * Retrieval eval harness: does the knowledge selector pick the right module
 * for how real users actually phrase things?
 *
 * Each case is a verbatim-style Russian gym question mapped to the set of
 * modules whose content actually answers it. The case passes when the live
 * selector (`getRelevantKnowledge` — KEYWORD_MAPPINGS + TF-IDF + synonyms +
 * anti-overlap) picks at least one acceptable module. "Any-of" semantics is
 * deliberate: many questions are genuinely answerable from two modules, and
 * pinning a single winner would freeze scoring internals rather than outcomes.
 *
 * When a case fails, the fix belongs in KEYWORD_MAPPINGS / KEYWORD_SYNONYMS —
 * not in relaxing the case. The bank doubles as the regression net for future
 * keyword edits: a keyword removal that silently orphans a phrasing fails here.
 */

