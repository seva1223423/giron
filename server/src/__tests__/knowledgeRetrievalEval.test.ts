describe('knowledge retrieval eval', () => {
  test.each(EVAL_SET)('«%s» → один из ожидаемых модулей', (question, acceptable) => {
    const { topics } = getRelevantKnowledge(question);
    const hit = topics.some((t) => acceptable.includes(t));
    if (!hit) {
      // Rich failure message: what won instead, to steer the keyword fix
      throw new Error(
        `MISS: «${question}»\n  ожидали: ${acceptable.join(' | ')}\n  выбрано: ${topics.join(', ') || '(ничего)'}`
      );
    }
    expect(hit).toBe(true);
  });

  test('банк покрывает все 25 модулей', () => {
    const covered = new Set(EVAL_SET.flatMap(([, mods]) => mods));
    expect(covered.size).toBe(25);
  });

  test('в банке не меньше 150 вопросов', () => {
    expect(EVAL_SET.length).toBeGreaterThanOrEqual(150);
  });
});
