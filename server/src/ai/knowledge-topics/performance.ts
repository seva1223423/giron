export interface WeeklySummary {
  totalWorkouts: number;
  totalVolume: number;
  totalDuration: number;
  musclesWorked: string[];
  avgRpe: number | null;
  completionRate: number; // % of planned workouts done
  volumeChange: number; // % change from prev week
  highlights: string[];
}
export function buildWeeklySummary(
  thisWeekWorkouts: Array<{
    name: string;
    completedAt: Date | null;
    totalVolume: number | null;
    durationMinutes: number | null;
    exercises: Array<{
      exercise: { name: string; primaryMuscles: string[] };
      sets: Array<{ rpe: number | null; completed: boolean }>;
    }>;
  }>,
  prevWeekVolume: number,
  plannedDays: number,
): WeeklySummary {
  const completed = thisWeekWorkouts.filter((w) => w.completedAt);
  const totalVolume = completed.reduce((s, w) => s + (w.totalVolume || 0), 0);
  const totalDuration = completed.reduce((s, w) => s + (w.durationMinutes || 0), 0);

  // Muscles worked
  const muscleSet = new Set<string>();
  for (const w of completed) {
    for (const ex of w.exercises) {
      ex.exercise?.primaryMuscles?.forEach((m) => muscleSet.add(m));
    }
  }

  // Average RPE
  let rpeSum = 0; let rpeCount = 0;
  for (const w of completed) {
    for (const ex of w.exercises) {
      for (const s of ex.sets) {
        if (s.rpe) { rpeSum += s.rpe; rpeCount++; }
      }
    }
  }

  const volumeChange = prevWeekVolume > 0
    ? Math.round(((totalVolume - prevWeekVolume) / prevWeekVolume) * 100)
    : 0;

  const highlights: string[] = [];
  if (completed.length >= plannedDays && plannedDays > 0) {
    highlights.push(`✅ План выполнен: ${completed.length}/${plannedDays} тренировок`);
  } else if (completed.length > 0 && plannedDays > 0) {
    highlights.push(`⏳ ${completed.length}/${plannedDays} тренировок на этой неделе`);
  }
  if (volumeChange > 10) highlights.push(`📈 Объём +${volumeChange}% к прошлой неделе`);
  if (volumeChange < -15) highlights.push(`📉 Объём ${volumeChange}% к прошлой неделе`);
  if (rpeCount > 0 && rpeSum / rpeCount >= 9) highlights.push(`⚠️ Средний RPE ${(rpeSum / rpeCount).toFixed(1)} — возможна перегрузка`);

  return {
    totalWorkouts: completed.length,
    totalVolume: Math.round(totalVolume),
    totalDuration: Math.round(totalDuration),
    musclesWorked: [...muscleSet],
    avgRpe: rpeCount > 0 ? Math.round((rpeSum / rpeCount) * 10) / 10 : null,
    completionRate: plannedDays > 0 ? Math.round((completed.length / plannedDays) * 100) : 0,
    volumeChange,
    highlights,
  };
}
export function buildWeeklySummaryContext(summary: WeeklySummary): string {
  if (summary.totalWorkouts === 0) return '';

  const lines = [
    `Тренировок: ${summary.totalWorkouts}, объём: ${summary.totalVolume} кг, длительность: ${summary.totalDuration} мин`,
    `Мышцы: ${summary.musclesWorked.join(', ')}`,
    summary.avgRpe ? `Средний RPE: ${summary.avgRpe}` : null,
    summary.volumeChange !== 0 ? `Изменение объёма: ${summary.volumeChange > 0 ? '+' : ''}${summary.volumeChange}%` : null,
    ...summary.highlights,
  ].filter(Boolean);

  return `\n\n## 📊 ИТОГИ НЕДЕЛИ
${lines.join('\n')}
→ Используй при ответах о прогрессе, плане и мотивации.`;
}
export function summarizeChatThemes(
  recentMessages: Array<{ role: string; content: string }>,
): string {
  if (recentMessages.length < 4) return '';

  const userMessages = recentMessages.filter((m) => m.role === 'user').map((m) => m.content.toLowerCase());

  const themes: string[] = [];

  // Detect recurring topics
  const topicCounts: Record<string, number> = {};
  const topicPatterns: Record<string, RegExp> = {
    'питание': /питани|еда|калори|белок|кбжу|диет|перекус|завтрак|обед|ужин/,
    'тренировки': /тренировк|упражнен|подход|повтор|сет|программ|план/,
    'боль/травма': /болит|боль|травм|повредил|дискомфорт/,
    'мотивация': /мотивац|лень|устал|не хочу|бросить|настроен/,
    'вес тела': /вес|похуд|набор|масс|сушк/,
    'техника': /техник|как делать|правильно|форма|ошибк/,
    'программа': /программ|сплит|план|расписан|график/,
    'добавки': /добавк|протеин.*порош|креатин|витамин|бад/,
    'сон': /сон|спать|бессонниц|высыпа/,
    'стресс': /стресс|нервнич|тревог|психолог/,
  };

  for (const msg of userMessages) {
    for (const [topic, pattern] of Object.entries(topicPatterns)) {
      if (pattern.test(msg)) {
        topicCounts[topic] = (topicCounts[topic] || 0) + 1;
      }
    }
  }

  // Topics mentioned 2+ times are "themes"
  for (const [topic, count] of Object.entries(topicCounts)) {
    if (count >= 2) {
      themes.push(`${topic} (${count}× за сессию)`);
    }
  }

  if (themes.length === 0) return '';

  return `\n\n## 💬 ТЕМЫ РАЗГОВОРА
Пользователь чаще всего обсуждает: ${themes.join(', ')}
→ Приоритизируй эти темы в ответах. Проактивно предлагай помощь по ним.`;
}
export function buildConversationSummary(
  recentMessages: Array<{ role: string; content: string; createdAt: Date }>,
): string {
  if (recentMessages.length < 4) return '';

  // Analyze last 10 user messages for recurring topics
  const userMessages = recentMessages
    .filter((m) => m.role === 'user')
    .slice(0, 10)
    .map((m) => m.content.toLowerCase());

  const topicPatterns: Record<string, string[]> = {
    'тренировк': ['тренировка', 'программа', 'упражнение', 'подход', 'повтор', 'вес', 'жим', 'присед', 'тяга'],
    'питание': ['калори', 'белок', 'жир', 'углевод', 'еда', 'продукт', 'диета', 'кбжу'],
    'прогресс': ['прогресс', 'рекорд', 'результат', 'рост', 'изменения', 'динамика'],
    'здоровье': ['боль', 'травм', 'восстановл', 'отдых', 'сон', 'самочувств'],
    'мотивация': ['мотивац', 'лень', 'не хочу', 'цель', 'результат', 'стрик'],
  };

  const topicCounts: Record<string, number> = {};
  for (const msg of userMessages) {
    for (const [topic, keywords] of Object.entries(topicPatterns)) {
      if (keywords.some((k) => msg.includes(k))) {
        topicCounts[topic] = (topicCounts[topic] || 0) + 1;
      }
    }
  }

  const mainTopics = Object.entries(topicCounts)
    .filter(([, count]) => count >= 2)
    .sort((a, b) => b[1] - a[1])
    .map(([topic]) => topic);

  if (mainTopics.length === 0) return '';

  // Check for unanswered questions from user
  const lastUserMsg = userMessages[0];
  const hasQuestion = lastUserMsg && (lastUserMsg.includes('?') || lastUserMsg.includes('как') || lastUserMsg.includes('почему') || lastUserMsg.includes('сколько'));

  const lines: string[] = [];
  lines.push(`Основные темы бесед: ${mainTopics.join(', ')}`);

  if (hasQuestion) {
    lines.push(`💬 Пользователь задал вопрос — убедись что отвечаешь на него прямо.`);
  }

  return `\n\n## 💭 КОНТЕКСТ БЕСЕДЫ
${lines.join('\n')}`;
}
