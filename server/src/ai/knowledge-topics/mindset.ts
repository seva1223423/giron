export function getConfidenceDirective(user: any, message: string): string {
  const directives: string[] = [];

  // If user asks about medical/clinical things — lower confidence, recommend specialist
  const medicalPatterns = /(?:диагноз|лечени[ея]|лекарств|таблетк|уколы?|стероид|гормональн\s*тераpi|курс\s*(?:тест|стероид)|мрт|узи|рентген|анализ\s*(?:кров|мочи))/i;
  if (medicalPatterns.test(message)) {
    directives.push('⚠️ ОСТОРОЖНОСТЬ: Вопрос касается медицины. НЕ ставь диагнозы и НЕ назначай лечение. Дай общую информацию и ОБЯЗАТЕЛЬНО рекомендуй обратиться к спортивному врачу / эндокринологу / ортопеду.');
  }

  // If profile data is very incomplete — flag uncertainty in calculations
  const missingCritical = [];
  if (!user?.weightKg) missingCritical.push('вес');
  if (!user?.heightCm) missingCritical.push('рост');
  if (!user?.goal) missingCritical.push('цель');
  if (!user?.gender) missingCritical.push('пол');

  if (missingCritical.length >= 2) {
    directives.push(`⚠️ НЕПОЛНЫЕ ДАННЫЕ: Не хватает: ${missingCritical.join(', ')}. Любые расчёты (КБЖУ, программа) будут приблизительными — СКАЖИ ОБ ЭТОМ и попроси заполнить профиль.`);
  }

  // If user mentions contradictory goals
  const contradictions = [
    { pattern: /(?:похуде|сушк|дефицит).*(?:набр|масс|объём)/i, msg: 'Пользователь говорит одновременно про похудение и набор массы — уточни приоритет.' },
    { pattern: /(?:не\s*ем|голода|0\s*калорий).*(?:масс|сил|рос)/i, msg: 'Пользователь хочет расти но не ест — объясни почему это невозможно.' },
  ];
  for (const c of contradictions) {
    if (c.pattern.test(message)) {
      directives.push(`⚠️ ПРОТИВОРЕЧИЕ: ${c.msg}`);
    }
  }

  return directives.length > 0
    ? `\n\n## ⚖️ УВЕРЕННОСТЬ И ОГРАНИЧЕНИЯ\n${directives.join('\n')}`
    : '';
}
export function buildStreakMotivation(streak: number, totalWorkouts: number): string {
  if (streak <= 0 && totalWorkouts <= 0) return '';

  const lines: string[] = [];

  // Streak-based motivation
  if (streak === 0) {
    lines.push('🔄 Серия прервана. Мотивируй вернуться: «Каждый чемпион пропускал тренировки, но возвращался».');
  } else if (streak <= 3) {
    lines.push(`🔥 Серия: ${streak} ${streak === 1 ? 'тренировка' : streak <= 4 ? 'тренировки' : 'тренировок'}. Поддержи: «Отличное начало, продолжай!»`);
  } else if (streak <= 7) {
    lines.push(`🔥🔥 Серия: ${streak} тренировок! «Ты на волне! Неделя стабильных тренировок — это серьёзно.»`);
  } else if (streak <= 14) {
    lines.push(`🔥🔥🔥 Серия: ${streak} тренировок! «Две недели подряд — привычка формируется. Ты молодец!»`);
  } else if (streak <= 30) {
    lines.push(`🏆 Серия: ${streak} тренировок! «Месяц регулярных тренировок — это уже образ жизни!»`);
  } else {
    lines.push(`👑 СЕРИЯ: ${streak} тренировок! «${streak} тренировок подряд — ты железный! Такая дисциплина вдохновляет.»`);
  }

  // Milestone motivation
  const milestones = [10, 25, 50, 100, 200, 365, 500];
  for (const m of milestones) {
    if (totalWorkouts >= m - 2 && totalWorkouts <= m) {
      lines.push(`🎯 Почти ${m} тренировок всего! (сейчас ${totalWorkouts}) — отметь этот момент!`);
      break;
    }
    if (totalWorkouts === m) {
      lines.push(`🎉 ${m} тренировок всего! Поздравь пользователя с этим достижением!`);
      break;
    }
  }

  if (lines.length === 0) return '';

  return `\n\n## 🏅 МОТИВАЦИЯ
${lines.join('\n')}
→ Используй для поддержания мотивации. Не навязывай — вплетай естественно в ответ.`;
}
export function calibrateConfidence(
  totalWorkouts: number,
  bodyWeightEntries: number,
  mealEntries: number,
  memoryCount: number,
): string {
  let dataLevel: 'minimal' | 'low' | 'moderate' | 'good' | 'rich';
  const score = totalWorkouts * 3 + bodyWeightEntries * 2 + mealEntries + memoryCount * 2;

  if (score < 10) dataLevel = 'minimal';
  else if (score < 30) dataLevel = 'low';
  else if (score < 80) dataLevel = 'moderate';
  else if (score < 200) dataLevel = 'good';
  else dataLevel = 'rich';

  const directives: Record<string, string> = {
    minimal: '⚠️ ДАННЫХ ОЧЕНЬ МАЛО. Будь осторожен с рекомендациями. Задавай больше вопросов. Используй общие советы, а не персонализированные. Не делай выводов о прогрессе.',
    low: '⚠️ Мало данных. Рекомендации ориентировочные. Объясняй что для точных советов нужно больше тренировок/замеров.',
    moderate: 'Средний объём данных. Можно давать персонализированные советы, но отмечай неопределённость в прогнозах.',
    good: 'Хороший объём данных. Персонализация надёжна. Можно делать уверенные рекомендации по программам и питанию.',
    rich: 'Богатая история данных. Максимальная персонализация. Можно выявлять тренды, паттерны, давать точные рекомендации.',
  };

  return `\n\n## 📊 УРОВЕНЬ ДАННЫХ: ${dataLevel.toUpperCase()} (${score} баллов)
${directives[dataLevel]}`;
}
export function detectMoodAndModify(
  message: string,
  lastMessages: Array<{ content: string; role: string }>,
): string {
  const text = (message + ' ' + lastMessages.filter((m) => m.role === 'user').slice(0, 2).map((m) => m.content).join(' ')).toLowerCase();

  // Negative mood indicators
  const tiredWords = ['устал', 'усталость', 'нет сил', 'вымотан', 'не выспал', 'разбит', 'нет энергии', 'сонный', 'выжат'];
  const stressedWords = ['стресс', 'нервничаю', 'дедлайн', 'завал', 'аврал', 'давление', 'тревог', 'перегруз'];
  const painWords = ['болит', 'боль', 'ноет', 'тянет', 'дискомфорт', 'защемил', 'потянул', 'хрустит'];
  const motivatedWords = ['заряжен', 'энергия', 'мотивац', 'хочу жечь', 'давай тяжёлую', 'готов к бою', 'отличное настроение'];
  const demotivatedWords = ['не хочу', 'лень', 'скучно', 'надоело', 'без мотивации', 'не вижу смысл', 'бросить'];

  let mood: string | null = null;
  let directive = '';

  if (tiredWords.some((w) => text.includes(w))) {
    mood = 'tired';
    directive = '😴 Пользователь устал. Предложи ЛЁГКУЮ тренировку (50-60% от обычного объёма), больше разминки, или день отдыха. Не дави.';
  } else if (stressedWords.some((w) => text.includes(w))) {
    mood = 'stressed';
    directive = '😰 Пользователь в стрессе. Тренировка поможет! Предложи что-то среднее по интенсивности — не слишком тяжёлое, но достаточно для разрядки. Акцент на кардио или функционал.';
  } else if (painWords.some((w) => text.includes(w))) {
    mood = 'pain';
    directive = '🩹 Пользователь ощущает боль/дискомфорт. ОБЯЗАТЕЛЬНО спроси где именно болит. НЕ рекомендуй нагрузку на эту область. Предложи замену или отдых. При сильной боли — рекомендуй врача.';
  } else if (motivatedWords.some((w) => text.includes(w))) {
    mood = 'motivated';
    directive = '🔥 Пользователь мотивирован! Поддержи энтузиазм. Можно предложить более интенсивную тренировку, PR-попытку, или новое сложное упражнение.';
  } else if (demotivatedWords.some((w) => text.includes(w))) {
    mood = 'demotivated';
    directive = '😔 Пользователь потерял мотивацию. НЕ дави. Покажи его прогресс (PRs, streak). Предложи мини-тренировку (15-20мин). Напомни зачем он начал. Будь тёплым и поддерживающим.';
  }

  if (!mood) return '';

  return `\n\n## 🎭 НАСТРОЕНИЕ: ${mood.toUpperCase()}
${directive}`;
}
export function trackSplitAdherence(
  recentWorkouts: Array<{
    name: string;
    exercises: Array<{
      exercise: { primaryMuscles: string[] };
    }>;
    scheduledDate: Date | null;
    completedAt: Date | null;
  }>,
  programType: string | null,
): string {
  if (!programType || recentWorkouts.length < 4) return '';

  // Detect actual muscle groups trained per session
  const sessions = recentWorkouts.slice(0, 8).map(w => {
    const muscles = new Set<string>();
    for (const ex of w.exercises) {
      for (const m of ex.exercise?.primaryMuscles ?? []) muscles.add(m);
    }
    return { name: w.name, muscles: Array.from(muscles), date: w.completedAt };
  });

  // Check for repeated muscle groups too close together
  const issues: string[] = [];
  for (let i = 0; i < sessions.length - 1; i++) {
    for (let j = i + 1; j < Math.min(i + 3, sessions.length); j++) {
      const overlap = sessions[i].muscles.filter(m => sessions[j].muscles.includes(m));
      if (overlap.length >= 3 && sessions[i].date && sessions[j].date) {
        const daysBetween = Math.abs(
          (sessions[i].date!.getTime() - sessions[j].date!.getTime()) / 86400000
        );
        if (daysBetween <= 1) {
          issues.push(`Одни и те же мышцы (${overlap.slice(0, 2).join(', ')}) тренировались 2 дня подряд`);
        }
      }
    }
  }

  if (issues.length === 0) {
    return `\n\n## ✅ СОБЛЮДЕНИЕ СПЛИТА\nПользователь хорошо следует своему сплиту (${programType}). Отметь это при случае.`;
  }

  return `\n\n## ⚠️ СОБЛЮДЕНИЕ СПЛИТА
Замечены отклонения от сплита (${programType}):
${issues.slice(0, 2).map(i => `- ${i}`).join('\n')}
Напомни о важности дней восстановления между тренировками одних и тех же мышц (48-72 часа).`;
}
