export function estimateSleepQuality(
  recentWorkouts: Array<{
    completedAt: Date | null;
    totalVolume: number | null;
    durationMinutes: number | null;
  }>,
): string {
  if (recentWorkouts.length < 3) return '';

  const completedWithTime = recentWorkouts
    .filter((w) => w.completedAt)
    .map((w) => ({
      hour: new Date(w.completedAt!).getHours(),
      volume: w.totalVolume || 0,
      duration: w.durationMinutes || 0,
    }));

  if (completedWithTime.length < 3) return '';

  // Detect late-night training pattern (after 22:00)
  const lateWorkouts = completedWithTime.filter((w) => w.hour >= 22 || w.hour < 5);
  const lateRatio = lateWorkouts.length / completedWithTime.length;

  // Detect inconsistent training times (high variance in start hour)
  const hours = completedWithTime.map((w) => w.hour);
  const avgHour = hours.reduce((a, b) => a + b, 0) / hours.length;
  const hourVariance = hours.reduce((sum, h) => sum + Math.pow(h - avgHour, 2), 0) / hours.length;

  // Detect performance dips (declining volume over consecutive workouts)
  const volumes = completedWithTime.map((w) => w.volume);
  let consecutiveDeclines = 0;
  for (let i = 1; i < Math.min(volumes.length, 5); i++) {
    if (volumes[i - 1] > 0 && volumes[i] < volumes[i - 1] * 0.85) consecutiveDeclines++;
  }

  const warnings: string[] = [];

  if (lateRatio > 0.3) {
    warnings.push('🌙 Частые тренировки поздно вечером (>22:00) — могут ухудшать качество сна');
  }
  if (hourVariance > 20) {
    warnings.push('🔀 Сильно «плавающее» время тренировок — нестабильный режим может влиять на сон');
  }
  if (consecutiveDeclines >= 2) {
    warnings.push('📉 Падение объёма в последних тренировках — возможный признак недосыпа');
  }

  if (warnings.length === 0) return '';

  return `\n\n## 😴 КАЧЕСТВО СНА (косвенная оценка)
${warnings.join('\n')}
→ Если уместно, спроси пользователя о режиме сна. Рекомендуй 7-9 часов, стабильный график, тренировки не позже чем за 2ч до сна.`;
}
export function buildHydrationReminder(
  lastWorkoutDurationMin: number | null,
  userWeightKg: number | null,
  userGoal: string | null,
): string {
  if (!userWeightKg) return '';

  // Base recommendation: 30-35 ml per kg
  const baseMl = Math.round(userWeightKg * 33);
  let extraMl = 0;

  if (lastWorkoutDurationMin) {
    // Add ~500ml per 30 min of training
    extraMl = Math.round((lastWorkoutDurationMin / 30) * 500);
  }

  const totalMl = baseMl + extraMl;
  const totalL = (totalMl / 1000).toFixed(1);

  // Don't always show — only if training day or specific goals
  if (!lastWorkoutDurationMin && userGoal !== 'WEIGHT_LOSS') return '';

  return `\n\n## 💧 ГИДРАТАЦИЯ
Рекомендация: ${totalL} л воды сегодня (базовая ${(baseMl / 1000).toFixed(1)} л${extraMl > 0 ? ` + ${(extraMl / 1000).toFixed(1)} л за тренировку` : ''}).
${userGoal === 'WEIGHT_LOSS' ? 'Вода помогает контролировать аппетит и ускоряет метаболизм.' : ''}
Напомни о воде если пользователь говорит о тренировке или питании.`;
}
export function analyzeSleepImpact(
  recentWorkouts: Array<{
    startedAt: Date | null;
    completedAt: Date | null;
    durationMinutes: number | null;
  }>,
): string {
  if (recentWorkouts.length < 3) return '';

  // Detect late-night training (after 21:00)
  const lateWorkouts = recentWorkouts.filter(w => {
    if (!w.startedAt) return false;
    const hour = w.startedAt.getHours();
    return hour >= 21;
  });

  // Detect very early training (before 6:00)
  const earlyWorkouts = recentWorkouts.filter(w => {
    if (!w.startedAt) return false;
    const hour = w.startedAt.getHours();
    return hour < 6;
  });

  const insights: string[] = [];

  if (lateWorkouts.length >= 2) {
    insights.push('Частые тренировки после 21:00 могут ухудшать сон. Интенсивная нагрузка повышает кортизол и температуру тела.');
    insights.push('Рекомендация: если тренируешься поздно, делай лёгкое кардио или стретчинг вместо силовой.');
  }

  if (earlyWorkouts.length >= 2) {
    insights.push('Ранние тренировки (до 6:00) — отлично для дисциплины, но убедись что спишь 7-8 часов.');
  }

  if (insights.length === 0) return '';

  return `\n\n## 😴 ВЛИЯНИЕ НА СОН
${insights.join('\n')}
Упоминай сон только если это релевантно разговору.`;
}
