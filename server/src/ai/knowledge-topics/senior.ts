export function getAgingAndTraining(message: string): string {
  const kw = ['тренировки в возрасте', 'силовой тренинг после 40', 'силовой тренинг после 50', 'старение и мышцы', 'саркопения', 'тренировки для пожилых'];
  if (!kw.some(k => message.toLowerCase().includes(k))) return '';
  return `
**Силовые тренировки и возраст:**

**Физиология старения:**
Саркопения: потеря 1-2% мышечной массы/год после 30 лет без тренировок
Снижение: анаболические гормоны (тестостерон -1%/год после 30), нейромышечная эффективность
Но: мышцы ВСЕГДА адаптируются к нагрузке, в любом возрасте

**Ключевые исследования:**
Fiatarone et al. (1994): 90-летние пациенты после 10 недель силовых увеличили силу на 174%
Fragala et al. (2019): NSCA позиция — силовые тренинг снижает смертность на 23% у 65+

**Адаптации программы после 40-50:**
Больше разминки (15-20 мин) — суставы медленнее «разогреваются»
Увеличить отдых между подходами (2-3 мин → 3-5 мин)
Приоритет технике над весом — риск травм выше
Добавить мобилити-работу (10-15 мин/сессия)
Снизить частоту до 2-3 раз/нед для каждой группы (восстановление дольше)

**Питание:**
Повышенная доза белка: 1.6-2.4 г/кг (анаболическая резистентность требует больше)
Лейцин: 3-4 г на приём пищи (пороговая доза для mTOR у пожилых)
Витамин D: 2000-4000 МЕ/день (дефицит → снижение силы)
Креатин: особенно эффективен для 50+ (James et al. meta-analysis)
`;
}
