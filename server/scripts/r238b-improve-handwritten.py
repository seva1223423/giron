def build_steps_block(steps: list[str], indent: int) -> str:
    """Render as multiline `steps: [\\n      'a',\\n      'b',\\n    ],`"""
    pad = ' ' * indent
    inner = '\n'.join(f"{pad}  '{s}'," for s in steps)
    return f"steps: [\n{inner}\n{pad}],"


def main() -> None:
    path = 'prisma/seed-recipes.ts'
    with open(path, encoding='utf-8') as f:
        src = f.read()

    applied = 0
    not_found = []

    for name, new_steps in FIXES:
        # Find the recipe block by name. Use a more robust regex that
        # captures id...steps:[...]...tags and replaces only the steps part.
        # We match the unique `name: '<exact name>',` line first, then
        # locate its `steps: [...],` after it.
        pat = re.compile(
            rf"(name:\s*'{re.escape(name)}',[\s\S]*?)"
            rf"(steps:\s*\[[\s\S]*?\],)",
        )
        match = pat.search(src)
        if not match:
            not_found.append(name)
            continue
        # Determine current indent of `steps:` (number of leading spaces on that line)
        # to preserve formatting.
        steps_start = match.start(2)
        line_start = src.rfind('\n', 0, steps_start) + 1
        indent = steps_start - line_start
        new_block = build_steps_block(new_steps, indent)
        src = src[:match.start(2)] + new_block + src[match.end(2):]
        applied += 1

    with open(path, 'w', encoding='utf-8') as f:
        f.write(src)

    print(f'Applied: {applied}/{len(FIXES)}')
    if not_found:
        print('Not found:')
        for n in not_found:
            print(f'  - {n}')


if __name__ == '__main__':
    main()
